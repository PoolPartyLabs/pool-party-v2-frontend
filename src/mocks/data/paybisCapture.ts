/**
 * @id PP-CORE-MCK-007 (POO-1598 S5)
 * @name Paybis captured purchase (mock, wire-level ground truth)
 * @implements-rules-version v1 (POO-1598 rules v1)
 *
 * The first real production Paybis capture (2026-08-17, EUR
 * buyer, card, captured by the S1-S4 instrumentation this same epic built on `pool-party-api`),
 * committed as a replayable fixture set. POO-1598's whole premise: every unknown that has blocked this
 * epic is a vendor behaviour nobody had observed, and a log a human has to transcribe is not a
 * deliverable, a fixture is. This module and its `paybisCapture/*.capture.json` siblings are that
 * fixture set, at the PAYBIS WIRE level: exactly what `pool-party-api`'s `TracedHttpService` recorded
 * on the outbound hop to `widget-api.paybis.com`, not pool-party-api's own (further-wrapped) DTO back
 * to this app. `paybisCapture.test.ts` proves the two are close enough to matter: every captured
 * payment-methods list parses through this app's real {@link onRampPaymentMethodsResponseSchema} and
 * every captured quote parses through the real {@link onRampQuoteResponseSchema}, both imported from
 * `@/lib/onramp/schemas` verbatim, not a copy. That is the strongest compatibility evidence available
 * without pool-party-api's own source in this repo.
 *
 * ## What is REAL and what is SYNTHETIC (`CR-CORE-027`)
 *
 * The capture arrived already boundary-redacted (`[redacted:user-ip]`, `[redacted:email]`,
 * `[redacted:partner-user-id]`, `[redacted:wallet-address]`), which this module leaves untouched: a
 * v3/request replay does not need those fields to look real, only to be present. On top of that
 * boundary redaction, `CR-CORE-027` requires the following to become SYNTHETIC before a capture is
 * committed, and this module does exactly that and nothing more:
 *
 *   - **Every `quoteId` and the one `requestId`** from the source capture
 *     are replaced with `mock-poo1598-*` tokens, chosen to self-label as mock per the
 *     `mock-service-blueprint` identifier rule. The replacement preserves every JOIN in the capture: the
 *     422 request still carries the synthetic id of the quote that produced it
 *     ({@link MOCK_PAYBIS_CAPTURE_QUOTE_10USDC_CARD_B}'s `id`), and the 201 request still carries the
 *     synthetic id of ITS quote ({@link MOCK_PAYBIS_CAPTURE_QUOTE_11USDC_CARD_B}'s `id`). A future mock
 *     service can replay quote-then-request exactly as the real buyer did.
 *   - **The masked wallet.** The source's `[redacted:wallet-address]` boundary placeholder is replaced
 *     with one deterministic, valid-format, self-evidently-mock address
 *     ({@link MOCK_PAYBIS_CAPTURE_WALLET}), generated by the same seeded-hash approach as
 *     `src/mocks/data/pools.ts`'s `mockAddress`, not a real address with characters changed.
 *   - **`requestId`, `country`/`countryCode`.** This specific capture never sent a `country`/
 *     `countryCode` field at all (checked directly against the source text), so there is nothing to
 *     synthesize there; recorded here so a reader does not go looking for a redaction that never
 *     applied.
 *
 * Every other figure, every fee, every minimum, every timestamp and every payment-method id
 * (`pool-party-credit-card`, `pool-party_bridgerpay_revolutpay`, …) is REAL, copied byte-for-byte from
 * the capture. This is the deliberate exception the identifiers make room for: realism applies to the
 * *observable values*, not to the correlators, so a real-mode integration bug is never confused with a
 * gap between an idealized mock and this fixture.
 *
 * ## One field the redaction ITSELF corrupted (`POO-1668`)
 *
 * `exchangeRate.rate` reads `"1.[redacted:card-number]"` on 4 of the 13 quote records
 * ({@link MOCK_PAYBIS_CAPTURE_QUOTE_100USDC}, {@link MOCK_PAYBIS_CAPTURE_QUOTE_9USDC},
 * {@link MOCK_PAYBIS_CAPTURE_QUOTE_5USDC}, {@link MOCK_PAYBIS_CAPTURE_QUOTE_255USDC}): the PAN scanner
 * matched a 16-digit Luhn-valid run that happens to start right after the decimal point. Copying that
 * string into a fixture would ship a value that was never a rate at all. The true instantaneous rate for
 * those four exact requests cannot be recovered, so this module does NOT fabricate one; instead it
 * substitutes the nearest-in-time INTACT rate this same capture actually observed,
 * `"1.1572441341898636"` (seen at 15:52:54 and 15:53:40, bracketing all four corrupted requests, which
 * span 15:51:07-15:53:03). The substitution is corroborated, not guessed: each corrupted record's sibling
 * `exchangeRateCryptoToFiat.rate` field survived redaction intact at `"0.86422203"` for all four, and
 * `1 / 0.86422203 ≈ 1.15708`, in the same neighbourhood as the substituted value. The other 9 quote
 * records carry their own genuinely intact, genuinely DIFFERENT rates
 * (`"1.1573782452263905"`, `"1.1575123873503157"`), left exactly as captured: this fixture does not
 * normalize a real, moving exchange rate into one number.
 *
 * ## The cases this capture exists to preserve
 *
 * 1. **A method priced AND refused in the same response** ({@link MOCK_PAYBIS_CAPTURE_QUOTE_10USDC_CARD_B},
 *    POO-1666's root cause): `pool-party-credit-card` appears in `paymentMethods` at EUR 10.53 AND in
 *    `paymentMethodErrors` ("at least 10.003001 USDC"). Its controlled twin at 11 USDC
 *    ({@link MOCK_PAYBIS_CAPTURE_QUOTE_11USDC_CARD_B}) carries NO `paymentMethodErrors` and is the exact
 *    quote the capture's 201 mint used. Both are kept, unmodified, on purpose.
 * 2. **SEPA is non-instant, by omission.** `pool-party-manual-bank-transfer` carries
 *    `labels: ["low-fee"]` only, never `"instant"`, and `minAmount.amount === "200.00"` EUR
 *    ({@link MOCK_PAYBIS_CAPTURE_METHODS_USDC_BASE}). This is the only real evidence behind the whole
 *    A7-b instant-only rule: there is no "1-2 business days" tag anywhere in a live Paybis payload.
 * 3. **The vendor minimum MOVES.** Across roughly four minutes the "at least N USDC per order" floor for
 *    card-family methods read `10.002` (9 USDC and 5 USDC quotes, ~15:52), then `10.003001` (the 10 USDC
 *    quotes, ~15:53-15:56), then back to `10.002` half an hour later (the 1 USDC quote, ~16:23). All
 *    three literal strings are kept on their own records below; nothing here averages or rounds them
 *    into one "the minimum is X" constant.
 * 4. **The service fee is near-FIXED below ~40 USDC, then roughly 4.4% above it.** The `credit-card`
 *    `fees.serviceFee.amount` reads EUR 1.86-1.88 at every one of 1, 5, 9, 10 and 11 USDC (1.86 / 1.87 /
 *    1.87 / 1.88 / 1.88 respectively), then EUR 3.83 / 4.02 / 7.84 / 9.76 at 100 / 105 / 205 / 255 USDC.
 *    All nine amounts are kept so this shape stays visible rather than collapsing to a single
 *    spot-checked ratio.
 *
 * ## Layout
 *
 * `src/mocks/data/paybisCapture/*.capture.json` hold the raw, redacted-then-synthesized wire bodies,
 * one file per endpoint shape, mirroring the established `*.dev.capture.json` convention
 * (`src/lib/onramp/fixtures/currencyPairsToBuy.dev.capture.json`, `PP-CORE-LIB-096`): a capture is
 * recorded data, not a hand-written literal, and stays in its own file so a diff against a future
 * re-capture is legible. This module is the typed, documented surface over them; it changes no runtime
 * behaviour and is not wired into `src/lib/services/index.ts` or any hook (S5 is fixtures, the mock
 * SERVICE that replays them is separate follow-up work).
 *
 * PP-MOCK: static, captured fixture data. Not read by any production code path today.
 */
