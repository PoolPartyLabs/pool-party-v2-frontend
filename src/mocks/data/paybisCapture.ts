/** Find a captured quote record by its (synthetic) quote id. Pure lookup, no I/O, no mutation. */
export function findPaybisCaptureQuoteById(quoteId: string): PaybisCaptureQuoteRecord | undefined {
  return MOCK_PAYBIS_CAPTURE_QUOTES.find((record) => record.responseBody.id === quoteId);
}
