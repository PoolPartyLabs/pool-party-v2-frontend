/**
 * All 13 captured `POST /v2/quote` round trips, in original capture order. Covers every amount the
 * capture exercised (1, 5, 9, 10, 11, 100, 105, 205, 255 USDC), including the 10 USDC and 11 USDC
 * amounts requested more than once (a listing quote and one or two method-pinned quotes each), because
 * the repeats are exactly where the controlled priced-and-refused pair lives (see the module header).
 */
export const MOCK_PAYBIS_CAPTURE_QUOTES: readonly PaybisCaptureQuoteRecord[] = quotesCapture;

/**
 * A named quote at a fixed, known-good position in {@link MOCK_PAYBIS_CAPTURE_QUOTES}. A runtime check
 * rather than a non-null assertion: `noUncheckedIndexedAccess` makes bracket access `| undefined`
 * regardless of how confident the caller is, and this throws with a clear reason instead of silently
 * exporting `undefined` under a named constant if the capture array is ever edited to a different
 * length. Every call site below passes a literal index into the FIXED, already-verified capture.
 */
function requireCaptureQuote(index: number): PaybisCaptureQuoteRecord {
  const record = MOCK_PAYBIS_CAPTURE_QUOTES[index];
  if (!record) {
    throw new Error(`paybisCapture: expected a captured quote record at index ${index}`);
  }
  return record;
}

