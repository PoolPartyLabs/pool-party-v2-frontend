/** One `{ amount, currencyCode }` money object, the wire's convention everywhere it prices something. */
export interface PaybisWireMoney {
  amount: string;
  currencyCode: string;
}

/**
 * One entry of `GET /v2/payment-methods/{from}/{to}`, exactly as Paybis sends it (before this app's own
 * {@link onRampPaymentMethodsResponseSchema} strips `id`/`name`/`fees`, POO-1603's note on
 * `wirePaymentMethodSchema`). Kept in full here because a captured wire body is the point: `fees` (the
 * rate/flat MODEL) is visible beside the quote's own priced `serviceFee` so a reader can compare the
 * two without guessing at the model Paybis actually uses.
 */
export interface PaybisWirePaymentMethodListEntry {
  paymentMethod: string;
  displayName: string;
  id: string;
  name: string;
  icon: string;
  minAmount: PaybisWireMoney;
  maxAmount: PaybisWireMoney;
  fees: { amount: string; isPercent: boolean };
  labels: string[];
}

/** One priced method inside a `POST /v2/quote` response. */
export interface PaybisWireQuotePaymentMethod {
  id: string;
  name: string;
  amountTo: PaybisWireMoney;
  amountFrom: PaybisWireMoney;
  amountToEquivalent: PaybisWireMoney;
  fees: {
    networkFee: PaybisWireMoney;
    serviceFee: PaybisWireMoney;
    totalFee: PaybisWireMoney;
  };
  feesInCrypto: {
    networkFee: PaybisWireMoney;
    serviceFee: PaybisWireMoney;
    totalFee: PaybisWireMoney;
  };
  expiration: string;
  expiresAt: string;
}

/** One method the quote could NOT price, in Paybis' own words. */
export interface PaybisWireQuoteMethodError {
  paymentMethod: string;
  error: { message: string; code: string };
}

/** The full `POST /v2/quote` response body, wire-shaped (synthetic `id`, see the module header). */
export interface PaybisWireQuoteResponse {
  id: string;
  currencyCodeTo: string;
  currencyCodeFrom: string;
  requestedAmount: PaybisWireMoney;
  requestedAmountType: string;
  paymentMethods: PaybisWireQuotePaymentMethod[];
  paymentMethodErrors?: PaybisWireQuoteMethodError[];
  exchangeRate: { from: string; to: string; rate: string };
  exchangeRateCryptoToFiat: { from: string; to: string; rate: string };
}

/** The `POST /v2/quote` request body this app actually sent for one captured record. */
export interface PaybisWireQuoteRequestBody {
  currencyCodeFrom: string;
  currencyCodeTo: string;
  amount: string;
  directionChange: string;
  isReceivedAmount: boolean;
  /** Absent = a LISTING quote (every method priced at once); present = pinned to one method. */
  paymentMethod?: string;
}

/** One captured quote round trip, request and response together, in original capture order. */
export interface PaybisCaptureQuoteRecord {
  /** Position in the original 19-record trace (0-indexed); stable across re-reads of the source. */
  sourceIndex: number;
  requestBody: PaybisWireQuoteRequestBody;
  responseBody: PaybisWireQuoteResponse;
}

/** The `POST /v3/request` body this app sends to mint a purchase (synthetic `quoteId`/wallet). */
export interface PaybisWireRequestBody {
  partnerUserId: string;
  userIp: string;
  quoteId: string;
  email: string;
  locale: string;
  cryptoWalletAddress: { address: string; currencyCode: string };
  paymentMethod: string;
  passwordless: boolean;
}

/** A refused `POST /v3/request` (HTTP 422): the quote could not be minted. */
export interface PaybisWireRequestErrorResponse {
  message: string;
  code: string;
  errors: Array<{ message: string; code: string; property_path: string }>;
}

/** An accepted `POST /v3/request` (HTTP 201): the id the widget opens with. */
export interface PaybisWireRequestSuccessResponse {
  requestId: string;
}

